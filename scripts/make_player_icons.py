"""Writes lib/core/ui/harbor_icons.g.dart from Harbor's player icons (task 9.2).

Harbor (MIT, github.com/HarborCommunity/Harbor) draws its player with a set
of white 512x512 SVG icons in public/player-icons/. Kyndrel keeps their
path data and paints it with a CustomPainter, so the icons are exact,
tintable and need no asset loading.

    python3 scripts/make_player_icons.py <harbor checkout>
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "core" / "ui" / "harbor_icons.g.dart"
NS = "{http://www.w3.org/2000/svg}"


def circle(cx, cy, rx, ry):
    return (f"M{cx - rx},{cy}a{rx},{ry} 0 1,0 {2 * rx},0"
            f"a{rx},{ry} 0 1,0 {-2 * rx},0Z")


def transform_of(el):
    """(scale, dx, dy) for the one group transform the icons use."""
    t = el.get("transform")
    if not t:
        return None
    m = re.fullmatch(r"translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\) "
                     r"translate\(([-\d.]+) ([-\d.]+)\)", t)
    if not m:
        return None  # The ellipse's tiny rotation: ignored.
    tx, ty, s, ux, uy = map(float, m.groups())
    return (s, tx + s * ux, ty + s * uy)


def paths(svg):
    out = []

    def walk(el, tr):
        tr = transform_of(el) or tr
        tag = el.tag.replace(NS, "")
        if tag == "path":
            out.append((el.get("d"), tr))
        elif tag == "circle":
            r = float(el.get("r"))
            out.append((circle(float(el.get("cx")), float(el.get("cy")), r, r), tr))
        elif tag == "ellipse":
            out.append((circle(float(el.get("cx")), float(el.get("cy")),
                               float(el.get("rx")), float(el.get("ry"))), tr))
        for child in el:
            walk(child, tr)

    walk(ET.parse(svg).getroot(), None)
    return out


def dart_name(stem):
    parts = re.split(r"[-]+", stem)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def main():
    src = Path(sys.argv[1]) / "public" / "player-icons"
    lines = [
        "// Generated by scripts/make_player_icons.py from Harbor's player",
        "// icons (MIT, github.com/HarborCommunity/Harbor). Do not edit.",
        "",
        "import 'package:kyndrel/core/ui/harbor_icon.dart';",
        "",
        "/// Harbor's player icons, 512 × 512, filled white (task 9.2).",
        "abstract final class HarborIcons {",
    ]
    for svg in sorted(src.glob("*.svg")):
        name = dart_name(svg.stem)
        items = []
        for d, tr in paths(svg):
            d = re.sub(r"\s+", " ", d).strip()
            t = "" if tr is None else f", scale: {tr[0]}, dx: {tr[1]}, dy: {tr[2]}"
            items.append(f"    HarborIconPath('{d}'{t}),")
        lines.append(f"  static const {name} = HarborIconData([")
        lines += items
        lines.append("  ]);")
        lines.append("")
    lines[-1] = "}"
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
