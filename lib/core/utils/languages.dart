/// `eng` → `English`, `pt-BR` → `Portuguese (Brazil)`, `und` → `Unknown`.
/// Unknown codes come back upper-cased.
String languageName(String? code) {
  if (code == null || code.trim().isEmpty) return 'Unknown';
  final parts = code.trim().toLowerCase().split(RegExp('[-_]'));
  final base = parts.first;
  if (base == 'und' || base == 'unk' || base == 'mis') return 'Unknown';
  final two = _threeToTwo[base] ?? base;
  final name = _names[two];
  if (name == null) return code.toUpperCase();
  if (parts.length > 1) {
    final region = _regions[parts[1]] ?? parts[1].toUpperCase();
    return '$name ($region)';
  }
  return name;
}

/// Two-letter code for a 639-2 code, or the input if already two letters.
String? languageCode2(String? code) {
  if (code == null || code.isEmpty) return null;
  final base = code.toLowerCase().split(RegExp('[-_]')).first;
  return _threeToTwo[base] ?? (base.length == 2 ? base : null);
}

/// The three-letter code (ISO 639-2) for a two-letter one, as subtitle
/// sites use them ("ar" → "ara").
String? languageCode3(String? code) {
  final two = languageCode2(code);
  if (two == null) return null;
  for (final e in _threeToTwo.entries) {
    if (e.value == two) return e.key;
  }
  return null;
}
